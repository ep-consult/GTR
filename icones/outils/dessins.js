// LES 42 ICÔNES, DESSINÉES À LA MAIN dans le repère 24×24 (marge cible 1).
// Coordonnées lues sur les références quadrillées et sondées (comparer.js
// grille / sonde), jamais un contour extrait de l'image : chaque forme est
// composée à la main (polygones, arrondis, cercles, bandes). Chaque entrée
// rend 1 à 3 chemins ; un chemin est une liste de sous-chemins réunis
// (remplissage nonzero : les évidements tournent à l'envers, trou = true, et
// restent transparents ; un évidement est toujours posé DANS un plein).
const F = require('./forme.js');
const { poly, lisse, cercle, ellipse, boite, capsule, barre, effile, arcEpais, croissant, deplace, pivote, miroir, aplatir, bandes, epais } = F;
// pose des points décrits dans un repère local (x le long de l'axe, y en
// travers) sur un axe partant de (ox, oy) avec l'angle a (degrés)
const surAxe = (pts, ox, oy, a) => pivote(deplace(pts, ox, oy), a, ox, oy);
// profil symétrique le long d'un axe : [[x, demi-largeur, vif?], ...] → points
const profilPts = (prof) => prof.map((p) => [p[0], -p[1], p[2]]).concat(prof.slice().reverse().map((p) => [p[0], p[1], p[2]]));
const P1 = (x, y, ox, oy, a) => surAxe([[x, y]], ox, oy, a)[0].slice(0, 2);
// découpe un contour adouci en bandes et rend les morceaux
const enBandes = (pts, a, centres, e) => bandes(aplatir(pts), a, centres, e).map((m) => poly(m));

